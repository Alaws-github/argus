// Builds the index at the bottom of docs/LESSONS.md from docs/lessons/*.md, and
// checks every lesson is well formed: a kebab-case slug used once, a tag
// (bug, correction or design) and an "Enforced by:" line.
//   npm run lessons          rewrite the index
//   npm run check:lessons    fail if the index is stale or a lesson is malformed (also runs the code checks)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'docs/lessons');
const indexFile = resolve(root, 'docs/LESSONS.md');
const write = process.argv.includes('--write');

const problems = [];
const seen = new Map();
const sections = [];
for (const f of readdirSync(dir)
  .filter((x) => x.endsWith('.md'))
  .sort((a, b) => (a === 'general.md' ? -1 : b === 'general.md' ? 1 : a.localeCompare(b)))) {
  const lines = readFileSync(resolve(dir, f), 'utf8').replace(/\r/g, '').split('\n');
  const items = [];
  lines.forEach((l, i) => {
    if (!l.startsWith('### ')) return;
    const m = l.match(/^### ([a-z0-9]+(?:-[a-z0-9]+)*) `(bug|correction|design)`$/);
    if (!m) {
      problems.push(`${f}:${i + 1} heading must be "### kebab-slug \`bug|correction|design\`": ${l}`);
      return;
    }
    if (seen.has(m[1])) problems.push(`${f}:${i + 1} slug ${m[1]} is already used in ${seen.get(m[1])}`);
    seen.set(m[1], f);
    const body = [];
    for (let j = i + 1; j < lines.length && !lines[j].startsWith('#'); j++) body.push(lines[j]);
    const enf = body.find((b) => b.startsWith('**Enforced by:**'));
    if (!enf) problems.push(`${f}:${i + 1} ${m[1]} has no "**Enforced by:**" line`);
    else if (!/^\*\*Enforced by:\*\* (check \S+|test \S+|code \S+|none - .+)/.test(enf))
      problems.push(
        `${f}:${i + 1} ${m[1]}: Enforced by must start with check <name>, test <path>, code <path> or none - <why>`,
      );
    const checked = enf && /^\*\*Enforced by:\*\* (check|test|code) /.test(enf) ? ` (${enf.split(' ')[2]})` : '';
    items.push(`- \`${m[1]}\` \`${m[2]}\`${checked}`);
  });
  sections.push(`### [${f}](lessons/${f}) (${items.length})\n\n${items.join('\n')}`);
}

const total = seen.size;
const index = `<!-- lessons-index:start -->\n_Generated by \`npm run lessons\` from \`docs/lessons/*.md\`. Do not edit by hand. ${total} lessons._\n\n${sections.join('\n\n')}\n<!-- lessons-index:end -->`;
const doc = readFileSync(indexFile, 'utf8').replace(/\r/g, '');
const next = doc.replace(/<!-- lessons-index:start -->[\s\S]*<!-- lessons-index:end -->/, index);

if (write) {
  writeFileSync(indexFile, next);
  console.log(`Index rebuilt: ${total} lessons.`);
} else if (next !== doc) problems.push('docs/LESSONS.md index is out of date: run npm run lessons');

if (problems.length) {
  console.error(problems.map((p) => `LESSONS: ${p}`).join('\n'));
  process.exit(1);
}
if (!write) console.log(`Lessons OK: ${total} lessons, index up to date.`);
